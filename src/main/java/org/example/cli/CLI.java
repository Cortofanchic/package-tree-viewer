package org.example.cli;

/**
 * Утилитарный класс для вывода сообщений в консоль и управления завершением приложения.
 * <p>
 * Предоставляет статические методы для форматированного вывода информации, ошибок и исключений,
 * а также для корректного завершения программы с ненулевым кодом возврата.
 * </p>
 */
public class CLI {
    /**
     * Выводит сообщение об ошибке в стандартный поток вывода (System.out) с префиксом {@code [ERROR]}
     * и немедленно завершает работу приложения с кодом возврата 1.
     *
     * @param error Текст сообщения об ошибке.
     */
    public static void exitWithError(String error){
        System.out.println("[ERROR] " + error);
        System.exit(1);
    }

    /**
     * Выводит информационное сообщение в стандартный поток вывода с префиксом {@code [INFO]}.
     *
     * @param info Текст информационного сообщения.
     */
    public static void printInfo(String info){
        System.out.println("[INFO] " + info);
    }

    /**
     * Выводит сообщение об исключении в стандартный поток вывода с префиксом {@code [EXCEPTION]}.
     *
     * @param exc Текст сообщения об исключении.
     */
    public static void printExc(String exc){
        System.out.println("[EXCEPTION] " + exc);
    }

    /**
     * Выводит переданную строку в стандартный поток вывода без каких-либо префиксов.
     * <p>
     * Используется для вывода чистого текста, например, при печати результатов,
     * графов или дерева зависимостей.
     * </p>
     *
     * @param str Строка для вывода.
     */
    public static void printClear(String str){
        System.out.println(str);
    }
}
